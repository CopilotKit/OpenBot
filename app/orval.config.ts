/**
 * Generates the browser's API client from api/openapi.yaml: `bun run api:generate` at the root.
 *
 * Into app/src/lib/api/generated, checked in. CI regenerates it and fails when the result differs from
 * what is committed, so the client can never drift from the spec, and a build never depends on a
 * generator run it did not see.
 *
 * - `openbot`: the request functions, TanStack Query hooks and options, the types, and MSW handlers
 *   with fake data for tests. Every request goes through `apiRequest` (lib/api/request.ts), which is
 *   built on lib/client.ts.
 * - `openbotZod`: Zod schemas for every request and response, for checking a payload against the
 *   contract.
 */
import { defineConfig } from "orval";

const input = { target: "../api/openapi.yaml" };
const header = () => [
  "Generated by Orval from api/openapi.yaml. Do not edit: change the spec and run `bun run api:generate`.",
];

export default defineConfig({
  openbot: {
    input,
    output: {
      mode: "tags-split",
      target: "src/lib/api/generated/openbot.ts",
      schemas: "src/lib/api/generated/model",
      client: "react-query",
      httpClient: "fetch",
      // Header parameters, Idempotency-Key among them, become typed arguments a caller must pass.
      headers: true,
      // A Bot id from a package can hold characters a path segment cannot; each stays one segment.
      urlEncodeParameters: true,
      mock: {
        // The spec's own examples where it has them, so a test reads a Bot that looks like one.
        generators: [{ type: "msw", useExamples: true }],
      },
      clean: true,
      override: {
        header,
        mutator: { path: "src/lib/api/request.ts", name: "apiRequest" },
        fetch: { includeHttpResponseReturnType: false },
        query: { signal: true },
      },
    },
    hooks: { afterAllFilesWrite: "bunx biome format --write" },
  },
  openbotZod: {
    input,
    output: {
      mode: "tags-split",
      target: "src/lib/api/generated/openbot.ts",
      client: "zod",
      fileExtension: ".zod.ts",
      override: { header },
    },
    hooks: { afterAllFilesWrite: "bunx biome format --write" },
  },
});
