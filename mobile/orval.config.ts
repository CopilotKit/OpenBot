/**
 * Generates the phone app's API client from api/openapi.yaml: `bun run api:generate` at the root.
 *
 * Only the areas the app's screens use, by the spec's tags, so the phone carries the part of the API it speaks: add a
 * tag here when a screen starts using another area. Into src/api/generated, checked in. CI regenerates it and fails when
 * the result differs from what is committed, so the app can never call an address the spec does not have.
 *
 * Plain functions over fetch: the app keeps its own loading (src/use-load.ts) and installs nothing new. Every request
 * goes through `apiRequest` (src/api/request.ts): to the deployment the app was built for, with the signed-in session's
 * cookie, and with a fresh Idempotency-Key on every write unless the caller sends its own to retry with. The key is the
 * mutator's to add rather than a typed argument (`headers` is off), as it always was on the phone.
 */
import { defineConfig } from "orval";

export default defineConfig({
  mobile: {
    input: {
      target: "../api/openapi.yaml",
      filters: {
        tags: [
          "Approval rules",
          "Approvals",
          "Bot grants",
          "Bots",
          "Check-ins",
          "Computers",
          "Conversations",
          "Devices",
          "Memory",
          "Organization settings",
          "Organizations",
          "Routines",
          "Skills",
          "Tasks",
        ],
      },
    },
    output: {
      mode: "tags-split",
      target: "src/api/generated/openbot.ts",
      schemas: "src/api/generated/model",
      client: "fetch",
      httpClient: "fetch",
      // A Bot id from a package can hold characters a path segment cannot; each stays one segment.
      urlEncodeParameters: true,
      // The app's own tsconfig extends Expo's, which is installed with the app and not where the client is generated, so
      // the options that shape the output are Expo's, stated here.
      tsconfig: {
        compilerOptions: {
          esModuleInterop: true,
          module: "preserve",
          moduleResolution: "bundler",
          target: "esnext",
        },
      },
      clean: true,
      override: {
        header: () => [
          "Generated by Orval from api/openapi.yaml. Do not edit: change the spec and run `bun run api:generate`.",
        ],
        mutator: { path: "src/api/request.ts", name: "apiRequest" },
        fetch: { includeHttpResponseReturnType: false },
      },
    },
    hooks: { afterAllFilesWrite: "bunx biome format --write" },
  },
});
