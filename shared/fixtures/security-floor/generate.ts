/**
 * Writes cases.json: signed floors and what every app must decide about each, read by the TypeScript
 * tests (shared/tests/security-floor.test.ts) and OpenBot Desktop's Rust tests
 * (desktop/src-tauri/src/security_floor.rs), so both verify the same bytes the same way.
 *
 *   bun shared/fixtures/security-floor/generate.ts
 *
 * Signed with a key made for this run alone and thrown away: no app trusts it, and nothing outside
 * these tests can be signed with it.
 */
import { generateKeyPairSync } from "node:crypto";
import { writeFileSync } from "node:fs";
import { join } from "node:path";
import { publicKeyOf, signFloor } from "../../../scripts/security-floor-sign";
import type { SecurityFloor } from "../../security-floor";

function pair() {
  const { privateKey } = generateKeyPairSync("ed25519");
  const pem = privateKey.export({ format: "pem", type: "pkcs8" }).toString();
  return { pem, publicKey: publicKeyOf(pem) };
}

const trusted = pair();
const other = pair();

const floor = (serial: number, release: string): SecurityFloor => ({
  serial,
  issued: "2026-11-17T00:00:00.000Z",
  floors: {
    desktop: release,
    backend: release,
    mobile: release,
    recorder: release,
  },
  cloud: ["https://cloud.openbot.example"],
});

const text = (value: unknown) => `${JSON.stringify(value, null, 2)}\n`;
const current = signFloor(floor(2, "1.1.2"), trusted.pem);
const older = signFloor(floor(1, "1.1.1"), trusted.pem);
const tamperedPayload = Buffer.from(current.payload, "base64")
  .toString("utf8")
  .replace('"desktop": "1.1.2"', '"desktop": "0.0.1"');
const wrongKind = (() => {
  const signed = signFloor(floor(3, "1.1.2"), trusted.pem);
  const payload = Buffer.from(signed.payload, "base64")
    .toString("utf8")
    .replace('"openbot-security-floor"', '"something-else"');
  return signFloor(
    JSON.parse(payload) as SecurityFloor,
    trusted.pem,
  ) as unknown as Record<string, string>;
})();

const cases = {
  $comment:
    "Generated by generate.ts with a throwaway key. publicKey is the only key the cases trust.",
  publicKey: trusted.publicKey,
  cases: [
    {
      name: "current",
      document: text(current),
      verifies: true,
      serial: 2,
      desktop: "1.1.2",
    },
    {
      name: "older",
      document: text(older),
      verifies: true,
      serial: 1,
      desktop: "1.1.1",
    },
    {
      name: "unsigned",
      document: text({ payload: current.payload }),
      verifies: false,
    },
    {
      name: "zero signature",
      document: text({
        payload: current.payload,
        signature: Buffer.alloc(64).toString("base64"),
      }),
      verifies: false,
    },
    {
      name: "tampered",
      document: text({
        payload: Buffer.from(tamperedPayload).toString("base64"),
        signature: current.signature,
      }),
      verifies: false,
    },
    {
      name: "other key",
      document: text(signFloor(floor(9, "1.1.2"), other.pem)),
      verifies: false,
    },
    {
      name: "not a floor",
      document: text(wrongKind),
      verifies: false,
    },
  ],
};

writeFileSync(join(import.meta.dir, "cases.json"), text(cases));
