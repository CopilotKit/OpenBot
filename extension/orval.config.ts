/**
 * Generates the Recorder's API client from api/openapi.yaml: `bun run api:generate` at the root.
 *
 * Only the operations the spec tags Recorder, so the extension carries the part of the API it speaks and no more. Into
 * src/shared/generated, checked in. CI regenerates it and fails when the result differs from what is committed, so the
 * Recorder can never call an address the spec does not have.
 *
 * Every request goes through `openbotRequest` (src/shared/openbot-client.ts): to the OpenBot the caller names, with the
 * connection's bearer, never a cookie, never following a redirect, and with a fresh Idempotency-Key on every write. The
 * key is the mutator's to add rather than a typed argument (`headers` is off), as it always was for the Recorder.
 */
import { defineConfig } from "orval";

export default defineConfig({
  recorder: {
    input: {
      target: "../api/openapi.yaml",
      filters: { tags: ["Recorder"] },
    },
    output: {
      mode: "single",
      target: "src/shared/generated/recorder.ts",
      client: "fetch",
      httpClient: "fetch",
      // A connection id can hold characters a path segment cannot; each stays one segment.
      urlEncodeParameters: true,
      clean: true,
      override: {
        header: () => [
          "Generated by Orval from api/openapi.yaml. Do not edit: change the spec and run `bun run api:generate`.",
        ],
        mutator: {
          path: "src/shared/openbot-client.ts",
          name: "openbotRequest",
        },
        fetch: { includeHttpResponseReturnType: false },
      },
    },
    hooks: { afterAllFilesWrite: "bunx biome format --write" },
  },
});
